#!/usr/bin/env python3
"""Split pages (Oct 2026). app.html is the one source of the beat-maker UI (all panels, all scripts).
This writes one page per section (beats.html, record.html, studio.html, …): same app, pinned to one panel via
<html data-solo>, with a big-touch page bar instead of the 10-tab strip. Run after editing app.html:
   python3 beats/tools/gen-pages.py"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'app.html')).read()
# (file, solo panel, part, title, short label)
PAGES = [
 ('beats.html',  'beats',  'beats',  'Beat Maker — pads, kits & sequencer', 'Beats'),
 ('record.html', 'beats',  'record', 'Record Vocals', 'Record'),
 ('studio.html', 'studio', '',       'Studio — multitrack', 'Studio'),
 ('loops.html',  'loops',  '',       'Keys Loops', 'Loops'),
 ('piano.html',  'piano',  '',       'Piano Roll', 'Piano'),
 ('mixer.html',  'mixer',  '',       'Mixer', 'Mixer'),
 ('master.html', 'master', '',       'Master', 'Master'),
 ('lyrics.html', 'lyrics', '',       'Lyrics', 'Lyrics'),
 ('video.html',  'video',  '',       'Video', 'Video'),
 ('vault.html',  'vault',  '',       'Vault', 'Vault'),
]
BAR = ['beats.html', 'record.html', 'studio.html', 'loops.html', 'master.html']
ver = re.search(r'app\.js\?v=([0-9a-z]+)', src).group(1)
nav_re = re.compile(r'<nav class="tabs" role="tablist">.*?</nav>', re.S)
for f, solo, part, title, short in PAGES:
    links = ['<a class="tab pg-hub" href="./" title="All pages">⌂ All pages</a>']
    for g, s2, p2, t2, sh in PAGES:
        if g not in BAR and g != f: continue
        if g == f:
            links.append('<button class="tab active" role="tab" data-tab="%s" aria-selected="true" aria-current="page">%s</button>' % (s2, sh))
        else:
            links.append('<a class="tab" href="%s">%s</a>' % (g, sh))
    nav = '<nav class="tabs pg-bar" aria-label="Pages">' + ''.join(links) + '</nav>'
    h = nav_re.sub(nav, src, 1)
    h = h.replace('<html lang="en">', '<html lang="en" data-solo="%s"%s>' % (solo, ' data-part="%s"' % part if part else ''), 1)
    h = re.sub(r'<title>.*?</title>', '<title>%s · Island Pin Beats</title>' % title, h, count=1)
    h = h.replace('href="https://madinc47-prog.github.io/beats/">', 'href="https://madinc47-prog.github.io/beats/%s">' % f, 1)
    h = h.replace('</head>', '  <link rel="stylesheet" href="pages.css?v=%s">\n</head>' % ver, 1)
    h = h.replace('</body>', '<script>(function(){var sh=document.getElementById("studio-host");if(sh&&document.documentElement.getAttribute("data-solo")==="studio")document.body.appendChild(sh);function f(){var h=document.getElementById("studio-host");if(h)document.documentElement.style.setProperty("--pg-top",Math.round(h.getBoundingClientRect().top+scrollY)+"px");}addEventListener("load",f);addEventListener("resize",f);setTimeout(f,1500);})();</script>\n</body>', 1)
    h = '<!-- GENERATED by tools/gen-pages.py from app.html — edit app.html, then regenerate -->\n' + h
    if solo == 'studio':  # full screen: no ecosystem pill over the timeline (⌂ All pages floats bottom-right)
        h = h.replace('<script type="module" src="../shared/ecosystem-nav.js"></script>', '', 1)
    open(os.path.join(ROOT, f), 'w').write(h)
print('pages', ver, len(PAGES))
